import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { expect, test } from "vite-plus/test";
import {
  loadConfig,
  parsePo,
  resolveMessagesForLocale,
  runExtractMessages,
} from "@pantoken/i18n-engine";
import { ENGLISH_UI_STRINGS, flattenStrings } from "../.vitepress/i18n.ts";
import { catalogMessages, writeCatalogMessages } from "./catalog-i18n.ts";
import { stageCatalogLocales } from "./stage-catalog-locales.ts";

const root = resolve(import.meta.dirname, "../..");

test("catalog descriptions and titles stay in sync with the docs chrome source", () => {
  expect(() => writeCatalogMessages(true)).not.toThrow();
  const messages = catalogMessages();
  const ui = new Map(flattenStrings(ENGLISH_UI_STRINGS).map(({ path, text }) => [path, text]));
  const pot = parsePo(readFileSync(join(root, "l10n/docs.chrome.pot"), "utf8"));
  const units = new Set(pot.map(({ msgctxt, msgid }) => JSON.stringify([msgctxt, msgid])));
  for (const [key, entry] of Object.entries(messages)) {
    expect(ui.get(key)).toBe(entry.message);
    expect(units.has(JSON.stringify([`docs.chrome:${key}`, entry.message]))).toBe(true);
  }
  expect(messages["a2uiCatalogDescriptions.PantokenButton"]).toBeDefined();
  expect(messages["registryBrowserItems.button.description"]).toBeDefined();
  expect(messages["registryBrowserItems.button.title"]).toBeDefined();
});

test("catalog prose is extracted and resolves translations with an English fallback", () => {
  const dir = mkdtempSync(join(tmpdir(), "catalog-i18n-"));
  try {
    const original = loadConfig(join(root, "i18n.config.json"));
    const config = {
      ...original,
      spaces: {
        ...original.spaces,
        "docs.chrome": {
          kind: "messages" as const,
          source: "chrome.json",
          sourceMerge: ["catalog.json"],
        },
      },
    };
    writeFileSync(join(dir, "chrome.json"), readFileSync(join(root, "docs/.vitepress/i18n.json")));
    writeFileSync(join(dir, "catalog.json"), JSON.stringify(catalogMessages()));
    const { potPath } = runExtractMessages(config, dir, "docs.chrome");
    const entries = parsePo(readFileSync(potPath, "utf8"));
    const keys = new Set(entries.map(({ msgctxt }) => msgctxt));
    for (const key of Object.keys(catalogMessages()))
      expect(keys.has(`docs.chrome:${key}`)).toBe(true);

    const key = "a2uiCatalogDescriptions.PantokenButton";
    const source = catalogMessages()[key]!.message;
    mkdirSync(join(dir, "l10n/hu"), { recursive: true });
    writeFileSync(
      join(dir, "l10n/hu/docs.chrome.po"),
      `msgctxt "docs.chrome:${key}"\nmsgid ${JSON.stringify(source)}\nmsgstr "Tesztleírás"\n`,
    );
    const resolved = resolveMessagesForLocale(config, dir, "docs.chrome", "hu").strings;
    expect(resolved[key]).toBe("Tesztleírás");
    expect(resolved["registryBrowserItems.button.description"]).toBe(
      catalogMessages()["registryBrowserItems.button.description"]!.message,
    );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("localized page shells are staged without overwriting authored pages", () => {
  const dir = mkdtempSync(join(tmpdir(), "catalog-pages-"));
  try {
    stageCatalogLocales(dir, ["hu"]);
    expect(readFileSync(join(dir, "hu/a2ui/index.md"), "utf8")).toContain("<A2uiCatalogBrowser />");
    const registry = join(dir, "hu/r/index.md");
    expect(readFileSync(registry, "utf8")).toContain("<RegistryBrowser />");
    const original = readFileSync(registry, "utf8");
    writeFileSync(registry, `${original}\nStale generated content\n`);
    stageCatalogLocales(dir, ["hu"]);
    expect(readFileSync(registry, "utf8")).toBe(original);
    writeFileSync(registry, "Authored page");
    expect(() => stageCatalogLocales(dir, ["hu"])).toThrow("Refusing to overwrite authored page");
    expect(readFileSync(registry, "utf8")).toBe("Authored page");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("localized page staging rejects symlinks without modifying their targets", () => {
  const dir = mkdtempSync(join(tmpdir(), "catalog-page-symlink-"));
  try {
    const target = join(dir, "authored.md");
    const source = "<!-- Generated by stage-catalog-locales.ts; do not edit. -->\nKeep this file";
    writeFileSync(target, source);
    mkdirSync(join(dir, "hu/a2ui"), { recursive: true });
    symlinkSync(target, join(dir, "hu/a2ui/index.md"));
    expect(() => stageCatalogLocales(dir, ["hu"])).toThrow();
    expect(readFileSync(target, "utf8")).toBe(source);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
