import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { LOCALE_THEMES, NON_ROOT_LOCALES } from "../.vitepress/i18n.ts";
import { runAsMain } from "../../scripts/release/cli.ts";

const marker = "<!-- Generated by stage-catalog-locales.ts; do not edit. -->";

/** Stage localized page shells; their UI strings come from docs.chrome. */
export function stageCatalogLocales(
  docsRoot = resolve(import.meta.dirname, ".."),
  locales: readonly string[] = NON_ROOT_LOCALES,
): void {
  for (const locale of locales) {
    const theme = LOCALE_THEMES[locale]!;
    for (const [route, component, title] of [
      ["a2ui", "A2uiCatalogBrowser", theme.a2uiCatalog.title],
      ["r", "RegistryBrowser", theme.registryBrowser.title],
    ]) {
      const directory = resolve(docsRoot, locale, route);
      const path = resolve(directory, "index.md");
      if (existsSync(path) && !readFileSync(path, "utf8").includes(marker)) {
        throw new Error(`Refusing to overwrite authored page: ${path}`);
      }
      mkdirSync(directory, { recursive: true });
      writeFileSync(
        path,
        `---\ntitle: ${JSON.stringify(title)}\nlayout: page\n---\n\n${marker}\n<${component} />\n`,
      );
    }
  }
}

runAsMain(import.meta.url, async () => stageCatalogLocales());
